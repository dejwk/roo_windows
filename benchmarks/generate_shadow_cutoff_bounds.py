#!/usr/bin/env python3
"""Generate 96 bytes of combined-alpha > 2 extents per supported zoom.

Straight-edge profiles bound rounded corners from above. Preserve each layer's
full reach: clipping the layers independently would lose visible combinations.
"""
import csv
from fractions import Fraction
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader((root/'benchmarks/shadow_parameters.csv').open()))
source = (root/'src/roo_windows/decoration/shadow_lookup_tables.h').read_text()
tables = [list(map(int, re.findall(r'\d+', re.search(
    r'k'+name+r'\[256\] = \{(.*?)\};', source, re.S)[1])))
    for name in ('Key', 'Ambient')]
lines = ['// Generated by benchmarks/generate_shadow_cutoff_bounds.py; do not edit.',
         '// Combined alpha > 2. Entries are left/right, top, bottom pixel margins.']
for zoom in (75, 100, 150, 200):
    lines.append(('#if' if zoom == 75 else '#elif') + f' ROO_WINDOWS_ZOOM == {zoom}')
    lines.append('constexpr uint8_t kShadowCutoffBounds[32][3] = {')
    for row in rows:
        specs = []
        for layer, table in zip(('key', 'ambient'), tables):
            v = [Fraction(row[f'{layer}_{m}_dp'])*Fraction(zoom, 100)
                 for m in ('offset', 'blur', 'spread')]
            offset, sigma, spread = [int(x*factor+Fraction(1,2))
                                    for x, factor in zip(v, (16, 8, 16))]
            scale = (255*4096+3*sigma)//(6*sigma) if sigma else 0
            last = max(i for i,a in enumerate(table) if a)
            reach = spread+((last+1-128)*4096-1)//scale if scale else 0
            specs.append((offset, spread, scale, reach, table))
        bounds = []
        for sign in (0, -1, 1):
            old = max(0, max((reach+sign*offset+8)//16
                            for offset,spread,scale,reach,table in specs))
            bound = 0
            for d in range(1, old+1):
                alphas = []
                for offset,spread,scale,reach,table in specs:
                    distance = d*16-8-sign*offset
                    index = max(0, min(255, (128*4096+(distance-spread)*scale)>>12))
                    alphas.append(table[index] if scale and distance <= reach else 0)
                k,a = alphas
                if k+a-(k*a+127)//255 > 2:
                    bound = d
            assert 0 <= bound <= 255
            bounds.append(bound)
        lines.append('  {'+', '.join(map(str,bounds))+'},')
    lines.append('};')
lines += ['#else', '#error "Unsupported zoom for shadow cutoff bounds"', '#endif', '']
p = root/'src/roo_windows/decoration/shadow_cutoff_bounds.h'
p.write_text('\n'.join(lines))
subprocess.run(['clang-format', '-i', str(p)], check=True)
