#!/usr/bin/env python3
"""Generate exact flash shadow gradients for each supported zoom and level."""
import json
import math
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
base = [round(255 * .5 * math.erfc((-3 + 6*i/255) / math.sqrt(2))) for i in range(256)]
luts = [[(v*opacity+127)//255 for v in base] for opacity in (77, 38)]
key = [(0,0,0),(1,2,0),(1,2,0),(1,3,0),(2,3,0),(4,4,0)]
ambient = [(0,0,0),(1,3,1),(2,6,2),(4,8,3),(6,10,4),(8,12,6)]


def scaled(n, zoom):
    return n*zoom//100


def parameters(level, zoom, layer):
    offset, blur, spread = (key if layer == 0 else ambient)[level]
    sigma = scaled(blur*8, zoom)
    scale = (255*4096+3*sigma)//(6*sigma)
    return scaled(offset*16, zoom), scaled(spread*16, zoom), scale


def opacity(distance, params, layer):
    _, spread, scale = params
    index = max(0, min(255, (128*4096+(distance-spread)*scale)>>12))
    return luts[layer][index]


def composite(values):
    k, a = values
    return k+a-(k*a+127)//255


def corner(u, v, radius, level, zoom, bottom):
    values=[]
    for layer in range(2):
        params=parameters(level,zoom,layer)
        dx=radius*16-(u*16+8)
        dy=radius*16-(v*16+8+(params[0] if bottom else -params[0]))
        distance=math.isqrt(dx*dx+dy*dy) if dx>0 and dy>0 else max(dx,dy)
        values.append(opacity(distance-radius*16,params,layer))
    return composite(values)


def array(name, values, typ='uint8_t'):
    return [f'alignas(4) const {typ} {name}[] = {{']+[ '  '+', '.join(map(str,values[i:i+20]))+',' for i in range(0,len(values),20)]+['};']

lines=['// Generated by benchmarks/generate_shadow_gradients.py; do not edit.', '']
footprints={}
for zoom in (75,100,150,200):
    condition=('#if ROO_WINDOWS_ZOOM < 100' if zoom==75 else
               '#elif ROO_WINDOWS_ZOOM < 150' if zoom==100 else
               '#elif ROO_WINDOWS_ZOOM < 200' if zoom==150 else '#else')
    lines.append(condition)
    limit=scaled(32,zoom)
    side=[]
    for level in range(1,6):
        for direction in range(3):  # horizontal, top, bottom
            for d in range(-limit,limit+1):
                values=[]
                for layer in range(2):
                    params=parameters(level,zoom,layer)
                    delta=0 if direction==0 else params[0] if direction==1 else -params[0]
                    values.append(opacity(d*16-8+delta,params,layer))
                side.append(composite(values))
    lines += [f'constexpr int kSideLimit = {limit};', f'constexpr int kSideStride = {2*limit+1};']
    lines += array('kSideGradients',side)
    lines += ['#if ROO_WINDOWS_EXPERIMENTAL_SHADOW_GRADIENTS == 2']
    metadata=[]
    corners=[]
    for level in range(1,6):
        params=[parameters(level,zoom,l) for l in range(2)]
        reaches=[]
        for layer in range(2):
            last=max(i for i,v in enumerate(luts[layer]) if v)
            reaches.append(params[layer][1]+((last+1-128)*4096-1)//params[layer][2])
        horizontal=max((reach+8)//16 for reach in reaches)
        top=max(0,max((reaches[l]-params[l][0]+8)//16 for l in range(2)))
        bottom=max(0,max((reaches[l]+params[l][0]+8)//16 for l in range(2)))
        max_offset=max(p[0] for p in params)
        min_offset=min(p[0] for p in params)
        for radius_dp in range(4,25,4):
            radius=scaled(radius_dp,zoom)
            for lower in (False,True):
                vmin=-(bottom if lower else top)
                # dy > 0 in at least one layer, with half-pixel sampling.
                vmax=(radius*16-9+(-min_offset if lower else max_offset))//16
                width=radius+horizontal
                height=max(0,vmax-vmin+1)
                start=len(corners)
                metadata.append((start,-horizontal,vmin,width,height))
                for v in range(vmin,vmin+height):
                    for u in range(-horizontal,radius):
                        corners.append(corner(u,v,radius,level,zoom,lower))
    lines += ['const CornerGradient kCornerGradients[] = {']
    lines += ['  {'+', '.join(map(str,m))+'},' for m in metadata]
    lines += ['};']
    lines += array('kCornerPixels',corners)
    lines += ['#endif']
    footprints[zoom]={'side_bytes':len(side),'corner_pixel_bytes':len(corners),'corner_descriptors':len(metadata),'corner_descriptor_bytes':len(metadata)*8}
lines += ['#endif','']
dest=root/'src/roo_windows/decoration/shadow_gradient_tables.h'
dest.write_text('\n'.join(lines))
subprocess.run(['clang-format', '-i', str(dest)], check=True)
results = root/'benchmarks/shadow_esp32s3/optimization_results'
results.mkdir(exist_ok=True)
(results/'gradient-storage.json').write_text(json.dumps(footprints,indent=2)+'\n')
print(json.dumps(footprints,indent=2))
