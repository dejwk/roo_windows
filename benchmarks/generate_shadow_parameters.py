#!/usr/bin/env python3
"""Generate the authoritative free-offset shadow recipes from frozen fits.

Reference heights: 0, 3, 5, 8, 10, 14 dp. Key uses free-intercept shifted
powers; ambient uses power laws. Zero elevation explicitly disables shadows.
"""
import csv
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
fits = json.loads((root / 'benchmarks/shadow_parameters_fit.json').read_text())
rows = []
for index in range(32):
    h = index / 2
    key = [max(0, f['A'] * (h-f['x0'])**f['alpha']-f['y0']) for f in fits['key']] + [0]
    ambient = [f['A'] * h**f['alpha'] for f in fits['ambient']]
    rows.append([0]*6 if index == 0 else key + ambient)
with (root / 'benchmarks/shadow_parameters.csv').open('w') as out:
    writer = csv.writer(out, lineterminator='\n')
    writer.writerow(['index', 'elevation_dp'] + [f'{layer}_{metric}_dp' for layer in ('key','ambient') for metric in ('offset','blur','spread')])
    for i, row in enumerate(rows):
        writer.writerow([i, i/2] + [f'{v:.12f}' for v in row])
lines = [
    '// Generated by benchmarks/generate_shadow_parameters.py; do not edit.',
    '// Selected free-offset fit at reference heights 0, 3, 5, 8, 10, 14 dp.',
    '// Row n is n/2 logical dp; row zero explicitly disables both layers.',
    '#pragma once', '', '#include "roo_windows/config.h"',
    '', 'namespace roo_windows::internal {', '',
    'struct LayerPreset { uint16_t offset_16; uint16_t sigma_16; uint8_t spread_16; };',
    '', '// Scale logical dp before rounding; evaluated entirely at compile time.',
    'constexpr LayerPreset MakeShadowPreset(double offset, double blur, double spread) {',
    'constexpr double scale = ROO_WINDOWS_ZOOM / 100.0;',
    'return {static_cast<uint16_t>(offset*scale*16+0.5),',
    'static_cast<uint16_t>(blur*scale*8+0.5), static_cast<uint8_t>(spread*scale*16+0.5)};',
    '}', '',
]
lines.insert(4, '#include <cstdint>')
for layer, name in enumerate(('Key', 'Ambient')):
    lines.append(f'constexpr LayerPreset k{name}Presets[32] = {{')
    for row in rows:
        lines.append('MakeShadowPreset(' + ', '.join(f'{v:.12f}' for v in row[layer*3:layer*3+3]) + '),')
    lines.append('};')
lines.append('}  // namespace roo_windows::internal')
p = root / 'src/roo_windows/decoration/shadow_parameters.h'
p.write_text('\n'.join(lines)+'\n')
subprocess.run(['clang-format','-i',str(p)],check=True)

subprocess.run(["python3", str(root / "benchmarks/generate_shadow_cutoff_bounds.py")], check=True)
