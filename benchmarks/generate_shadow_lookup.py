#!/usr/bin/env python3
"""Generate the bounded Gaussian edge integral and exactly equivalent baked LUTs."""
import math
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
base = [round(255 * .5 * math.erfc((-3 + 6*i/255) / math.sqrt(2)))
        for i in range(256)]
lines = ['// Generated by benchmarks/generate_shadow_lookup.py; do not edit.\n']
for name, opacity in [('kEdge', None), ('kKey', 77), ('kAmbient', 38)]:
    values = base if opacity is None else [(v*opacity+127)//255 for v in base]
    condition = '== 1' if opacity is None else '== 2'
    lines += [f'#if ROO_WINDOWS_EXPERIMENTAL_SHADOW_LUT_COUNT {condition}',
              f'SHADOW_LUT_STORAGE uint8_t {name}[256] = {{']
    lines += ['  ' + ', '.join(map(str, values[i:i+16])) + ',' for i in range(0,256,16)]
    lines += ['};', f'constexpr int {name}LastNonzero = {max(i for i, value in enumerate(values) if value != 0)};', '#endif', '']
destination = root/'src/roo_windows/decoration/shadow_lookup_tables.h'
destination.write_text('\n'.join(lines))
subprocess.run(['clang-format', '-i', str(destination)], check=True)
