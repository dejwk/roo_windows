#!/usr/bin/env python3
"""Validate the offline export and generate the public palette collection."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys


def validate(document, roles):
    """Reject incomplete palettes, non-opaque values, and ambiguous identities."""
    if document['format'] != 1:
        raise ValueError('Unsupported palette export format')
    ids = set()
    for preset in document['presets']:
        identity = preset['id']
        if not re.fullmatch(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*', identity) or identity in ids:
            raise ValueError(f'Invalid or duplicate preset ID: {identity}')
        ids.add(identity)
        for mode in ('light', 'dark'):
            colors = preset[mode]
            if set(colors) != set(roles):
                raise ValueError(f'{identity}/{mode}: roles differ from ColorScheme')
            for role, value in colors.items():
                if not re.fullmatch(r'0xFF[0-9A-F]{6}', value):
                    raise ValueError(f'{identity}/{mode}/{role}: expected opaque ARGB')
    if not ids:
        raise ValueError('Empty collection')


def generate(document, roles):
    """Render separate translation units so unused palettes can be omitted."""
    result = {}
    namespace = 'roo_windows::material3::schemes'
    directory = 'src/roo_windows/material3/schemes/'
    banner = ('// Generated by tools/theme_import/generate.py; do not edit.\n'
              '// FlexColorScheme 8.4.0, Mike Rydstrom, Copyright (c) 2020 - 2025.\n'
              '// BSD-3-Clause; see LICENSE.flex_color_scheme in this directory.\n')
    for preset in document['presets']:
        stem = preset['id'].replace('-', '_')
        function = ''.join(part.title() for part in preset['id'].split('-'))
        result[directory + stem + '.h'] = (
            banner + '#pragma once\n\n'
            '#include "roo_windows/material3/schemes/color_scheme_pair.h"\n\n'
            f'namespace {namespace} {{\n\n'
            f'/// Returns immutable {preset["name"]} palettes with static lifetime.\n'
            f'const ColorSchemePair& {function}();\n\n'
            f'}}  // namespace {namespace}\n')
        modes = []
        for mode in ('light', 'dark'):
            entries = '\n'.join(
                f'        .{role} = roo_display::Color({preset[mode][role]}),'
                for role in roles)
            modes.append(f'    .{mode} = {{\n{entries}\n    }},')
        result[directory + stem + '.cpp'] = (
            banner + f'#include "roo_windows/material3/schemes/{stem}.h"\n\n'
            f'namespace {namespace} {{\nnamespace {{\n\n'
            'constexpr ColorSchemePair kColors = {\n' + '\n'.join(modes) + '\n};\n\n'
            '}  // namespace\n\n'
            f'const ColorSchemePair& {function}() {{ return kColors; }}\n\n'
            f'}}  // namespace {namespace}\n')
    result[directory + 'catalog.h'] = (
        banner + '#pragma once\n\n#include <stddef.h>\n\n'
        '#include "roo_windows/material3/schemes/color_scheme_pair.h"\n\n'
        f'namespace {namespace} {{\n\n'
        '/// Named palette access for optional theme pickers. IDs are stable.\n'
        'struct SchemePreset {\n'
        '  const char* id;\n  const char* name;\n'
        '  const ColorSchemePair& (*colors)();\n};\n\n'
        f'inline constexpr size_t kPresetCount = {len(document["presets"])};\n\n'
        '/// Sorted by display name, ignoring case.\n'
        '/// Referencing the catalog retains every preset; use individual headers\n'
        '/// when the application needs only selected palettes.\n'
        'extern const SchemePreset kPresets[kPresetCount];\n\n'
        f'}}  // namespace {namespace}\n')
    catalog = sorted(document['presets'],
                     key=lambda preset: (preset['name'].casefold(), preset['id']))
    includes = ''.join(
        '#include "roo_windows/material3/schemes/'
        + p['id'].replace('-', '_') + '.h"\n' for p in catalog)
    entries = ''.join(
        f'    {{"{p["id"]}", "{p["name"]}", '
        + ''.join(part.title() for part in p['id'].split('-')) + '},\n'
        for p in catalog)
    result[directory + 'catalog.cpp'] = (
        banner + '#include "roo_windows/material3/schemes/catalog.h"\n\n'
        + includes + f'\nnamespace {namespace} {{\n\n'
        'const SchemePreset kPresets[kPresetCount] = {\n' + entries + '};\n\n'
        f'}}  // namespace {namespace}\n')
    rows = [
        "# Material 3 preset reference\n",
        "Generated by `tools/theme_import/generate.py` from the pinned "
        "FlexColorScheme export.\n",
        f"All {len(document['presets'])} named presets have light and dark "
        "palettes. Include paths below are relative to "
        "`roo_windows/material3/schemes/`; accessors belong to "
        "`roo_windows::material3::schemes`.\n",
        "| Preset | Header | Accessor | Stable ID | Upstream scheme |",
        "| --- | --- | --- | --- | --- |",
    ]
    for preset in catalog:
        stem = preset['id'].replace('-', '_')
        function = ''.join(part.title() for part in preset['id'].split('-'))
        rows.append(f"| {preset['name']} | `{stem}.h` | `{function}()` | "
                    f"`{preset['id']}` | `{preset['upstream_scheme']}` |")
    rows.append("\nSee [color theming](material3_color_theming.md) for installation "
                "and the [import instructions](../tools/theme_import/README.md) "
                "for generation settings and attribution.")
    result['docs/material3_scheme_reference.md'] = '\n'.join(rows) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    document = json.loads((Path(__file__).parent / 'palettes.json').read_text())
    header = (args.root / 'src/roo_windows/material3/theme.h').read_text()
    roles = re.findall(r'roo_display::Color (\w+);', header.split('constexpr')[0])
    if not roles:
        raise ValueError('Cannot discover ColorScheme fields')
    validate(document, roles)
    failed = []
    for relative, source in generate(document, roles).items():
        path = args.root / relative
        # Use the same repository formatting for generation and verification.
        formatted = source
        if path.suffix in ('.h', '.cpp'):
            formatted = subprocess.run(
                ['clang-format', f'--assume-filename={path}'], input=source,
                text=True, capture_output=True, check=True).stdout
        if args.check:
            if not path.exists() or path.read_text() != formatted:
                failed.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(formatted)
    if failed:
        sys.exit('Generated files differ:\n' + '\n'.join(failed))
    print(f'{"Verified" if args.check else "Generated"} '
          f'{len(document["presets"])} light/dark presets ({len(roles)} roles each)')


if __name__ == '__main__':
    main()
