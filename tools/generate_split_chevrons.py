#!/usr/bin/env python3
"""Generate the flash-backed split-button chevrons for supported zoom levels.

Run from the roo_windows root with:
  python3 tools/generate_split_chevrons.py > src/roo_windows/material3/button/internal/split_chevrons.cpp
"""

SLOTS = (22, 26, 38, 50)
ZOOMS = (75, 100, 150, 200)


def scaled(slot, zoom):
    if zoom == 75:
        return slot * 3 // 4
    if zoom == 150:
        return slot * 3 // 2
    return slot * zoom // 100


def pixels(slot, up):
    # The Material arrow_drop art has an ink footprint of 20 x 10 in a
    # 48 x 48 anchor. Supersampling keeps the edge soft at every zoom.
    width = max(2, round(slot * 20 / 48))
    height = max(2, round(slot * 10 / 48))
    left = (slot - width) // 2
    top = (slot - height) // 2
    result = []
    for y in range(height):
        row = []
        for x in range(width):
            covered = 0
            for sy in range(4):
                fy = (y + (sy + .5) / 4) / height
                span = fy if up else 1 - fy
                for sx in range(4):
                    fx = (x + (sx + .5) / 4) / width
                    if abs(fx - .5) <= span / 2:
                        covered += 1
            row.append(round(covered * 15 / 16))
        result += row
    return left, top, width, height, result


def encode(values):
    nibbles = []
    i = 0
    while i < len(values):
        value = values[i]
        if value in (0, 15):
            count = 1
            while i + count < len(values) and values[i + count] == value and count < 7:
                count += 1
            nibbles.append(count | (8 if value == 15 else 0))
            i += count
        else:
            nibbles.extend((0, value))
            i += 1
    if len(nibbles) % 2:
        nibbles.append(0)
    return [16 * a + b for a, b in zip(nibbles[::2], nibbles[1::2])]


print('// Generated by tools/generate_split_chevrons.py; do not edit by hand.')
print('#include "roo_windows/material3/button/internal/split_chevrons.h"')
print('#include "roo_windows/core/theme.h"')
print('namespace roo_windows::material3::internal {')
print('namespace {')
for zoom in ZOOMS:
    print(('#if' if zoom == 75 else '#elif') + f' ROO_WINDOWS_ZOOM == {zoom}')
    for dp in SLOTS:
        slot = scaled(dp, zoom)
        for up in (False, True):
            name = f'chevron_{dp}_{"up" if up else "down"}'
            left, top, width, height, values = pixels(slot, up)
            data = encode(values)
            print(f'const unsigned char {name}_data[] PROGMEM = {{')
            for i in range(0, len(data), 16):
                print('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i + 16]) + ',')
            print('};')
            print(f'const MonoIcon& {name}() {{')
            print('  static const MonoIcon icon(')
            print(f'      roo_display::Box({left}, {top}, {left + width - 1}, {top + height - 1}),')
            print(f'      roo_display::Box(0, 0, {slot - 1}, {slot - 1}),')
            print(f'      {name}_data, roo_display::Alpha4(roo_display::color::Black));')
            print('  return icon;')
            print('}')
    print()
print('#else')
print('#error "Unsupported split-button zoom"')
print('#endif')
print('}  // namespace')
print('const MonoIcon& SplitChevron(ButtonSize size, bool up) {')
print('  switch (size) {')
for size, dp in [('kExtraSmall', 22), ('kSmall', 22), ('kMedium', 26), ('kLarge', 38), ('kExtraLarge', 50)]:
    print(f'    case ButtonSize::{size}:')
    print(f'      return up ? chevron_{dp}_up() : chevron_{dp}_down();')
print('  }')
print('  return chevron_22_down();')
print('}')
print('}  // namespace roo_windows::material3::internal')
