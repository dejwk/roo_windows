void Switch::onClicked() {
  OnOffState target = isOn() ? OnOffState::kOff : OnOffState::kOn;
  state_ = (state_ & kFractionMask) | StateBits(target);
  startThumbTransition();
  Widget::onClicked();
}

void Switch::setOnOffState(OnOffState state) {
  if (onOffState() == state) return;
  context().animations().cancel(*this, kThumb);
  state_ = StateBits(state) | EndpointFraction(state);
  setDirty();
}

void Switch::setAppliedThumbFraction(int16_t fraction) {
  if (fraction < 0) fraction = 0;
  if (fraction > 256) fraction = 256;
  state_ = (state_ & kOnOffStateMask) | static_cast<uint16_t>(fraction);
}

void Switch::startThumbTransition() {
  const int16_t target = isOn() ? 256 : 0;
  const int16_t current = appliedThumbFraction();
  context().animations().cancel(*this, kThumb);
  if (current == target ||
      presentationState() != PresentationState::kPresented) {
    snapThumbToLogicalState();
    return;
  }
  AnimationSpec spec = AnimationSpec::value(
      static_cast<float>(current), static_cast<float>(target),
      roo_time::Millis(kSwitchAnimationMs));
  if (context().animations().start(*this, kThumb, spec) !=
      AnimationStatus::kOk) {
    snapThumbToLogicalState();
  }
}

void Switch::snapThumbToLogicalState() {
  context().animations().cancel(*this, kThumb);
  setAppliedThumbFraction(isOn() ? 256 : 0);
  setDirty();
}

int16_t Switch::currentThumbOffsetX() const {
  return (Scaled(19) * appliedThumbFraction() + 128) / 256;
}

roo_display::FpPoint Switch::getPointOverlayFocus() const {
  int16_t content_left = (width() - Scaled(42)) / 2;
  int16_t content_top = (height() - Scaled(24)) / 2;
  return roo_display::FpPoint{
      content_left + 0.5f * (float)(Scaled(24) - 1) + currentThumbOffsetX(),
      content_top + 0.5f * (float)(Scaled(24) - 1)};
}

void Switch::onAnimationFrame(AnimationTag tag, const AnimationSample& sample) {
  if (tag != kThumb) {
    BasicWidget::onAnimationFrame(tag, sample);
    return;
  }
  int16_t fraction = static_cast<int16_t>(sample.value + 0.5f);
  if (fraction == appliedThumbFraction()) return;
  setAppliedThumbFraction(fraction);
  setDirty();
}

void Switch::onPresentationChanged(const PresentationChange& change) {
  if (change.state == PresentationState::kPresented &&
      !change.detached_since_delivery) {
    return;
  }
  snapThumbToLogicalState();
}

void Switch::paint(PaintContext& ctx) const {
  const Theme& th = theme();
  ::roo_windows::material3::ColorToken bg_role = effectiveContainerRole();
  Color circleColor = isOn()
                          ? th.material3Theme().color.accentColorFor(bg_role)
                          : th.material3Theme().color.resolve(
                                ::roo_windows::material3::ColorToken::kSurface);
  Color sliderColor = isOn()
                          ? th.material3Theme().color.accentColorFor(bg_role)
                          : th.material3Theme().color.contentColorFor(bg_role);
  int16_t xoffset = currentThumbOffsetX();
#if ROO_WINDOWS_ZOOM >= 200
  auto slider = slider_48();
  auto circle = circle_48();
  auto shadow = circular_shadow_48();
#elif ROO_WINDOWS_ZOOM >= 150
  auto slider = slider_36();
  auto circle = circle_36();
  auto shadow = circular_shadow_36();
#elif ROO_WINDOWS_ZOOM >= 100
  auto slider = slider_24();
  auto circle = circle_24();
  auto shadow = circular_shadow_24();
#else
  auto slider = slider_18();
  auto circle = circle_18();
  auto shadow = circular_shadow_18();
#endif
  slider.color_mode().setColor(sliderColor);
  circle.color_mode().setColor(circleColor);
  // leaving shadow as black.
  Box outer(0, 0, Scaled(42) - 1, Scaled(24) - 1);
  auto composite = MakeDrawableRawStreamable(
      Overlay(outer, slider, kCenter | kMiddle,
              Overlay(shadow.anchorExtents(), shadow, kCenter | kMiddle, circle,
                      kCenter | kMiddle),
              kLeft.shiftBy(xoffset) | kMiddle));

  roo_display::Tile toggle(&composite, outer, kMiddle);
  ctx.drawTiled(toggle, bounds(), kCenter | kMiddle, isInvalidated());
}

Dimensions Switch::getSuggestedMinimumDimensions() const {
  return Dimensions(Scaled(42), Scaled(24));
}

